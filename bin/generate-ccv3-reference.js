function parseArgs(argv) {
    const o = {source: process.env.CCV3_SCHEMA_SOURCE || DEFAULT_SOURCE, locale: 'en', out: null};
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--source') o.source = argv[++i];
        else if (a === '--locale') o.locale = argv[++i];
        else if (a === '--out') o.out = argv[++i];
        else if (a === '--help' || a === '-h') {
            console.log('Usage: node bin/generate-ccv3-reference.js [--source <dir|url>] [--locale en|de] [--out <dir>]');
            process.exit(0);
        } else throw new Error(`Unknown argument: ${a}`);
    }
    if (!o.source) throw new Error('--source needs a value');
    if (!UI[o.locale]) throw new Error(`No UI strings for locale "${o.locale}" (available: ${Object.keys(UI).join(', ')})`);
    return o;
}

async function loadJSON(source, rel) {
    if (/^https?:\/\//i.test(source)) {
        const url = source.replace(/\/+$/, '') + '/' + rel;
        const res = await fetch(url);
        if (!res.ok) throw new Error(`Fetching ${url} failed: HTTP ${res.status}`);
        return res.json();
    }
    return JSON.parse(fs.readFileSync(path.join(source, rel), 'utf8'));
}

// ---------------------------------------------------------------------------
// Text helpers (MDX safe)
// ---------------------------------------------------------------------------
function dashes(s) {
    return String(s).replace(/\s*[\u2013\u2014]\s*/g, ' - ');
}

// Escapes text for MDX. Inline code spans are kept as they are (only pipes are escaped in cells).
function esc(text, cell) {
    let s = dashes(text == null ? '' : text);
    s = cell ? s.replace(/\s*\n+\s*/g, ' ') : s.replace(/\n{3,}/g, '\n\n');
    return s.split(/(`[^`]*`)/).map((part, i) => {
        if (i % 2 === 1) return cell ? part.replace(/\|/g, '\\|') : part;
        let p = part.replace(/\\/g, '\\\\').replace(/\{/g, '\\{').replace(/\}/g, '\\}').replace(/</g, '&lt;').replace(/>/g, '&gt;');
        if (cell) p = p.replace(/\|/g, '\\|');
        return p;
    }).join('').trim();
}

function code(v) {
    const s = dashes(String(v)).replace(/\s*\n+\s*/g, ' ').replace(/`/g, "'").replace(/\|/g, '\\|');
    return '`' + s + '`';
}

function sentence(s) {
    s = s.trim();
    return s && !/[.!?)"]$/.test(s) ? s + '.' : s;
}

function tpl(str, vars) {
    return str.replace(/\{(\w+)\}/g, (_, k) => vars[k]);
}

function table(head, rows) {
    return [
        '| ' + head.join(' | ') + ' |',
        '| ' + head.map(() => '---').join(' | ') + ' |',
        ...rows.map(r => '| ' + r.join(' | ') + ' |')
    ].join('\n');
}

function yamlStr(s) {
    return JSON.stringify(dashes(s).replace(/\s*\n+\s*/g, ' '));
}

// ---------------------------------------------------------------------------
// Generator
// ---------------------------------------------------------------------------
class Generator {
    constructor(schema, loc, locale) {
        this.s = schema;
        this.l = loc;
        this.locale = locale;
        this.ui = UI[locale];
        this.warnings = new Map(); // bucket -> Map(what -> count)
        this.typeIndex = new Map(schema.parameterTypes.map(p => [p.type, p]));
        this.basicIds = Object.keys(loc.parameterTypes || {}).filter(k => !this.typeIndex.has(k));
        this.extras = {};
    }

    warn(bucket, what) {
        if (!this.warnings.has(bucket)) this.warnings.set(bucket, new Map());
        const m = this.warnings.get(bucket);
        m.set(what, (m.get(what) || 0) + 1);
    }

    text(obj, field, bucket, what) {
        const v = obj && typeof obj[field] === 'string' ? obj[field].trim() : '';
        if (!v) this.warn(bucket, what);
        return v;
    }

    // ----- types
    typeKnown(id) {
        return this.typeIndex.has(id) || this.basicIds.includes(id) || id === 'ARRAY' || id === 'MAP';
    }

    typeName(id) {
        if (id === 'ARRAY') return this.ui.list;
        if (id === 'MAP') return this.ui.map;
        const t = this.l.parameterTypes && this.l.parameterTypes[id];
        if (t && t.name) return t.name;
        return this.basicIds.includes(id) ? this.ui.basicNames[id] || null : null;
    }

    typeRef(id, prefix, bucket) {
        const name = this.typeName(id);
        if (!name || !this.typeKnown(id)) {
            this.warn(bucket, 'type without localized name');
            return code(id);
        }
        return `[${esc(name, true)}](${prefix}#${id})`;
    }

    typeLabel(item, prefix, bucket) {
        if (item.type === 'ARRAY') {
            return item.content ? tpl(this.ui.listOf, {t: this.typeRef(item.content, prefix, bucket)}) : this.typeRef('ARRAY', prefix, bucket);
        }
        if (item.type === 'MAP') {
            if (item.content) {
                return tpl(this.ui.mapOf, {
                    k: this.typeRef(item.keyContent || 'STRING', prefix, bucket),
                    v: this.typeRef(item.content, prefix, bucket)
                });
            }
            return this.typeRef('MAP', prefix, bucket);
        }
        return this.typeRef(item.type, prefix, bucket);
    }

    // Name of one value of an enum type; falls back to the raw value in code.
    valueName(typeId, valueId) {
        const t = this.l.parameterTypes && this.l.parameterTypes[typeId];
        const v = t && t.values && t.values[valueId];
        if (v && v.name) return esc(v.name, true);
        return code(valueId);
    }

    constraints(item, siblings, bucket) {
        const ui = this.ui;
        const out = [];
        const range = (min, max, kRange, kMin, kMax) => {
            if (min != null && max != null) out.push(tpl(kRange, {a: min, b: max}));
            else if (min != null) out.push(tpl(kMin, {a: min}));
            else if (max != null) out.push(tpl(kMax, {b: max}));
        };
        range(item.minLength, item.maxLength, ui.lengthRange, ui.lengthMin, ui.lengthMax);
        range(item.min, item.max, ui.valueRange, ui.valueMin, ui.valueMax);
        range(item.minItems, item.maxItems, ui.itemsRange, ui.itemsMin, ui.itemsMax);
        if (item.pattern) out.push(tpl(ui.pattern, {p: code(item.pattern)}));
        if (Array.isArray(item.allowedValues) && item.allowedValues.length) {
            out.push(tpl(ui.allowed, {v: item.allowedValues.map(v => this.valueName(item.type, v)).join(', ')}));
        }
        if (item.default !== undefined && item.default !== null) {
            let d;
            if (typeof item.default === 'boolean') d = item.default ? ui.yes : ui.no;
            else if (typeof item.default === 'object') d = code(JSON.stringify(item.default));
            else if (this.typeIndex.get(item.type) && this.typeIndex.get(item.type).kind === 'ENUM') d = this.valueName(item.type, item.default);
            else d = code(item.default);
            out.push(tpl(ui.def, {v: d}));
        }
        if (item.showWhen && item.showWhen.input) {
            const ctrl = (siblings || []).find(x => x.id === item.showWhen.input);
            const ctrlName = ctrl && ctrl._name ? esc(ctrl._name, true) : code(item.showWhen.input);
            const vals = (item.showWhen.in || []).map(v => ctrl ? this.valueName(ctrl.type, v) : code(v)).join(', ');
            out.push(tpl(ui.showWhen, {i: ctrlName, v: vals}));
        }
        if (item.oneOfGroup && siblings) {
            const others = siblings.filter(x => x !== item && x.oneOfGroup === item.oneOfGroup).map(x => x._name ? esc(x._name, true) : code(x.id));
            if (others.length) out.push(tpl(ui.alternative, {v: others.join(', ')}));
        }
        return out.map(sentence);
    }

    // Attaches the localized name to schema items so cross references (showWhen, oneOfGroup) can use it.
    withNames(items, locItems, bucket, what) {
        return (items || []).map(i => {
            const li = locItems && locItems[i.id];
            const name = li && typeof li.name === 'string' && li.name.trim() ? li.name.trim() : '';
            if (!name) this.warn(bucket, `${what} name`);
            return Object.assign({}, i, {_name: name, _desc: this.text(li, 'description', bucket, `${what} description`)});
        });
    }

    paramTable(items, bucket, prefix, opts) {
        // opts.required: show Required column
        const ui = this.ui;
        const head = opts.required ? [ui.name, ui.type, ui.required, ui.details] : [ui.name, ui.type, ui.details];
        const rows = items.map(i => {
            const details = [];
            if (i._desc) details.push(sentence(esc(i._desc, true)));
            details.push(...this.constraints(i, items, bucket));
            if (opts.nullable && i.nullable) details.push(sentence(ui.mayBeEmpty));
            const cells = [i._name ? esc(i._name, true) : code(i.id), this.typeLabel(i, prefix, bucket)];
            if (opts.required) cells.push(i.optional ? ui.no : ui.yes);
            cells.push(details.join(' '));
            return cells;
        });
        return table(head, rows);
    }

    factsLine(item) {
        const ui = this.ui;
        const parts = [];
        if (item.requiredPermissions && item.requiredPermissions.length) {
            parts.push(`${ui.requiredPermissions}: ${item.requiredPermissions.map(p => this.valueName('PERMISSION_FLAG', p)).join(', ')}.`);
        }
        if (item.requiredIntents && item.requiredIntents.length) {
            parts.push(`${ui.requiredIntents}: ${item.requiredIntents.map(code).join(', ')}.`);
        }
        return parts.join(' ');
    }

    providesSentence(exposes) {
        if (!exposes) return '';
        const ex = Object.keys(exposes).map(k => {
            const e = exposes[k];
            return e.description ? `${esc(e.name || k, true)} (${esc(e.description, true).replace(/[.]$/, '')})` : esc(e.name || k, true);
        });
        return ex.length ? sentence(tpl(this.ui.provides, {v: ex.join(', ')})) : '';
    }

    branchesTable(action, la, bucket) {
        const ui = this.ui;
        const rows = [];
        for (const b of action.branches || []) {
            const lb = la && la.branches && la.branches[b.id];
            const name = lb && lb.name ? esc(lb.name, true) : code(b.id);
            if (!(lb && lb.name)) this.warn(bucket, 'branch name');
            const details = [];
            const d = this.text(lb, 'description', bucket, 'branch description');
            if (d) details.push(sentence(esc(d, true)));
            if (b.optional) details.push(sentence(ui.optional));
            const prov = this.providesSentence(lb && lb.exposesParameters);
            if (prov) details.push(prov);
            rows.push([name, details.join(' ')]);
        }
        if (action.dynamicBranches && la && la.dynamicBranches) {
            const metaIds = ((action.dynamicBranches.metaSchema || []).map(m => m.id)).filter(k => la.dynamicBranches[k]);
            for (const k of metaIds) {
                const e = la.dynamicBranches[k];
                const details = [];
                if (e.description) details.push(sentence(esc(e.description, true)));
                else this.warn(bucket, 'branch description');
                details.push(sentence(ui.dynamicBranch));
                const prov = this.providesSentence(la.dynamicBranches.exposesParameters);
                if (prov) details.push(prov);
                rows.push([e.name ? esc(e.name, true) : code(k), details.join(' ')]);
            }
        }
        return rows.length ? table([ui.name, ui.details], rows) : '';
    }

    renderItem(kind, item, bucket, prefix) {
        const ui = this.ui;
        const isTrigger = kind === 'triggers';
        const li = (isTrigger ? this.l.triggers : this.l.actions)[item.id] || {};
        const name = li.name && li.name.trim() ? li.name.trim() : (this.warn(bucket, `${isTrigger ? 'trigger' : 'action'} name`), item.id);
        const lines = [];
        lines.push(`### ${esc(name)} {#${item.id}}`);
        const desc = this.text(li, 'description', bucket, `${isTrigger ? 'trigger' : 'action'} description`);
        if (desc) lines.push('', esc(desc));
        const facts = this.factsLine(item);
        if (facts) lines.push('', facts);

        const sections = [];
        if (isTrigger) {
            const cfg = this.withNames(item.configSchema, li.config, bucket, 'setting');
            if (cfg.length) sections.push([ui.settings, this.paramTable(cfg, bucket, prefix, {required: true})]);
            const params = this.withNames(item.parameters, li.parameters, bucket, 'provided value');
            if (params.length) sections.push([ui.provided, this.paramTable(params, bucket, prefix, {nullable: true})]);
            const outs = this.withNames(item.outputs, li.outputs, bucket, 'output');
            if (outs.length) sections.push([ui.outputs, this.paramTable(outs, bucket, prefix, {nullable: true})]);
        } else {
            const ins = this.withNames(item.inputs, li.inputs, bucket, 'input');
            if (ins.length) sections.push([ui.inputs, this.paramTable(ins, bucket, prefix, {required: true})]);
            const outs = this.withNames(item.outputs, li.outputs, bucket, 'output');
            if (outs.length) sections.push([ui.outputs, this.paramTable(outs, bucket, prefix, {nullable: true})]);
            const br = this.branchesTable(item, li, bucket);
            if (br) sections.push([ui.branches, br]);
        }
        for (const [label, body] of sections) lines.push('', `**${label}**`, '', body);
        return lines.join('\n');
    }

    // ----- categories
    flatCategories() {
        const out = [];
        const walk = (list, parent) => list.forEach(c => {
            out.push({id: c.id, type: c.type || [], parent: parent ? parent.id : null});
            if (c.items) walk(c.items, c);
        });
        walk(this.s.categories, null);
        return out;
    }

    categoryText(id, parentId, field) {
        const holder = parentId ? (this.l.categories || {})[parentId] : (this.l.categories || {});
        const c = holder && holder[id];
        if (c && typeof c[field] === 'string' && c[field].trim()) return c[field].trim();
        const x = EXTRA_CATEGORIES[id];
        return x && x[field][this.locale] ? x[field][this.locale] : null;
    }

    categoryName(id, parentId) {
        return this.categoryText(id, parentId, 'name');
    }

    categoryDescription(id, parentId) {
        return this.categoryText(id, parentId, 'description');
    }

    humanize(id) {
        const s = id.replace(/-/g, ' ');
        return s.charAt(0).toUpperCase() + s.slice(1);
    }

    banner() {
        return `{/* ${BANNER_MARK}. Do not edit by hand. */}`;
    }

    readOverride(rel) {
        const base = this.locale === 'en' ? OVERRIDES : path.join(OVERRIDES, this.locale);
        const f = path.join(base, rel);
        if (!fs.existsSync(f)) return null;
        return fs.readFileSync(f, 'utf8').replace(/^---\n[\s\S]*?\n---\n/, '').trim();
    }

    pageHead(position, title, description) {
        return [
            '---',
            `sidebar_position: ${position}`,
            `title: ${yamlStr(title)}`,
            `sidebar_label: ${yamlStr(title)}`,
            `description: ${yamlStr(description)}`,
            '---'
        ].join('\n');
    }

    // Intro text for a category page: override file > fitting category description > generic line.
    categoryIntro(kind, cat, title, overrideRel) {
        let intro = this.readOverride(overrideRel);
        let plain = null;
        const generic = tpl(kind === 'triggers' ? this.ui.fallbackIntroTriggers : this.ui.fallbackIntroActions, {name: title});
        if (intro == null) {
            // Category texts are written for triggers on nested categories, so actions only reuse them where they fit.
            const fits = kind === 'triggers'
                ? cat.type.includes('TRIGGER')
                : cat.type.includes('ACTIONS') && (!cat.parent || !cat.type.includes('TRIGGER'));
            const d = fits || EXTRA_CATEGORIES[cat.id] ? this.categoryDescription(cat.id, cat.parent) : null;
            if (fits && !d) this.warn(cat.id, 'category description');
            plain = d;
            intro = d ? esc(d) : esc(generic);
        }
        return {intro, plain: (plain || generic).replace(/\s+/g, ' ')};
    }

    itemPage({kind, rel, position, title, intro, plain, items, bucket, depth}) {
        const prefix = '../'.repeat(depth) + 'value-types.md';
        const body = items.map(i => this.renderItem(kind, i, bucket, prefix)).join('\n\n');
        return {rel, content: `${this.pageHead(position, title, plain)}\n\n${this.banner()}\n\n${intro}\n\n${body}\n`};
    }

    categoryJson(rel, label, position) {
        // `key` keeps sidebar translation keys unique: the actions and triggers trees share category names.
        const key = 'ccv3-' + rel.replace(/\/_category_\.json$/, '').replace(/\//g, '-');
        const json = {label, key, position, collapsed: true, customProps: {generated: 'ccv3-reference'}};
        return {rel, content: JSON.stringify(json, null, 2) + '\n'};
    }

    generateReferencePages() {
        const pages = [];
        const known = new Set();
        const tops = [];
        const walkTop = (c) => {
            tops.push(c);
        };
        this.s.categories.forEach(walkTop);
        const mark = (c) => {
            known.add(c.id);
            (c.items || []).forEach(mark);
        };
        this.s.categories.forEach(mark);
        const extraIds = [];
        for (const it of [...this.s.triggers, ...this.s.actions]) {
            if (!known.has(it.category) && !extraIds.includes(it.category)) extraIds.push(it.category);
        }
        this.unknownCategories = extraIds;
        const allTops = [...tops, ...extraIds.map(id => ({id, type: [], items: []}))];

        for (const kind of ['triggers', 'actions']) {
            const items = this.s[kind];
            const of = (id) => items.filter(i => i.category === id);
            let pos = 0;
            for (const top of allTops) {
                const own = of(top.id);
                const children = (top.items || []).map(c => ({c, own: of(c.id)})).filter(x => x.own.length);
                if (!own.length && !children.length) continue;
                pos++;
                const topName = this.categoryName(top.id, null);
                if (!topName) this.warn(top.id, 'category name');
                const topTitle = topName || this.humanize(top.id);
                const topCat = {id: top.id, type: top.type || [], parent: null};
                const split = SPLIT_CATEGORIES[`${kind}/${top.id}`];

                if (!children.length && !split) {
                    const {intro, plain} = this.categoryIntro(kind, topCat, topTitle, `${kind}/${top.id}.md`);
                    pages.push(this.itemPage({kind, rel: `reference/${kind}/${top.id}.md`, position: pos, title: topTitle, intro, plain, items: own, bucket: top.id, depth: 2}));
                    continue;
                }
                const dir = `reference/${kind}/${top.id}`;
                pages.push(this.categoryJson(`${dir}/_category_.json`, topTitle, pos));
                if (split) {
                    const assigned = split.map(() => []);
                    for (const it of own) assigned[split.findIndex(g => g.match.test(it.id))].push(it);
                    this.unmatched = (assigned[assigned.length - 1] || []).map(i => i.id);
                    let gp = 0;
                    split.forEach((g, gi) => {
                        if (!assigned[gi].length) return;
                        gp++;
                        const title = g.name[this.locale];
                        let intro = this.readOverride(`${kind}/${top.id}/${g.id}.md`);
                        if (intro == null) intro = esc(g.intro[this.locale]);
                        pages.push(this.itemPage({kind, rel: `${dir}/${g.id}.md`, position: gp, title, intro, plain: g.intro[this.locale], items: assigned[gi], bucket: top.id, depth: 3}));
                    });
                    continue;
                }
                if (own.length) {
                    const {intro, plain} = this.categoryIntro(kind, topCat, topTitle, `${kind}/${top.id}.md`);
                    pages.push(this.itemPage({kind, rel: `${dir}/index.md`, position: 1, title: topTitle, intro, plain, items: own, bucket: top.id, depth: 3}));
                }
                children.forEach(({c, own: cOwn}, ci) => {
                    const name = this.categoryName(c.id, top.id);
                    if (!name) this.warn(c.id, 'category name');
                    const title = name || this.humanize(c.id);
                    const {intro, plain} = this.categoryIntro(kind, {id: c.id, type: c.type || [], parent: top.id}, title, `${kind}/${c.id}.md`);
                    pages.push(this.itemPage({kind, rel: `${dir}/${c.id}.md`, position: ci + 2, title, intro, plain, items: cOwn, bucket: c.id, depth: 3}));
                });
            }
        }
        return pages;
    }

    // ----- value types page
    typeSection(p, bucket) {
        const ui = this.ui;
        const lt = (this.l.parameterTypes || {})[p.type] || {};
        const basic = this.basicIds.includes(p.type);
        // Basic types only carry an example in the locale files; their names are static strings.
        const name = lt.name && lt.name.trim() ? lt.name.trim() : (basic && this.ui.basicNames[p.type]) || (this.warn(bucket, 'type name'), p.type);
        const lines = [`### ${esc(name)} {#${p.type}}`];
        const desc = basic ? '' : this.text(lt, 'description', bucket, 'type description');
        if (desc) lines.push('', esc(desc));
        const meta = [];
        if (lt.example) meta.push(tpl(ui.example, {v: code(lt.example)}) + '.');
        if (p.kind === 'UNION' && p.variants) meta.push(tpl(ui.either, {v: [...new Set(Array.isArray(p.variants) ? p.variants : Object.values(p.variants))].map(v => this.typeRef(v, '', bucket)).join(', ')}) + '.');
        if (p.extends && !p.kind && this.typeKnown(p.extends)) {
            meta.push(tpl(ui.extends, {v: this.typeRef(p.extends, '', bucket)}) + '.');
        }
        if (meta.length) lines.push('', meta.join(' '));
        if (p.kind === 'ENUM' && p.values && p.values.length) {
            const rows = p.values.map(v => {
                const lv = (lt.values || {})[v.id] || {};
                if (!lv.name) this.warn(bucket, 'enum value name');
                if (!lv.description) this.warn(bucket, 'enum value description');
                return [code(v.id), lv.name ? esc(lv.name, true) : '', lv.description ? esc(lv.description, true) : ''];
            });
            lines.push('', table([ui.value, ui.name, ui.details], rows));
        }
        if (p.properties && p.properties.length) {
            const props = this.withNames(p.properties, lt.properties, bucket, 'property');
            const rows = props.map(i => {
                const details = [];
                if (i._desc) details.push(sentence(esc(i._desc, true)));
                details.push(...this.constraints(i, props, bucket));
                if (i.nullable) details.push(sentence(ui.mayBeEmpty));
                const ex = lt.properties && lt.properties[i.id] && lt.properties[i.id].example;
                if (ex) details.push(sentence(tpl(ui.example, {v: code(ex)})));
                return [i._name ? esc(i._name, true) : code(i.id), this.typeLabel(i, '', bucket), details.join(' ')];
            });
            lines.push('', table([ui.property, ui.type, ui.details], rows));
        }
        return lines.join('\n');
    }

    generateValueTypes() {
        const ui = this.ui;
        const bucket = 'value-types';
        const groups = {basic: [], enums: [], objects: [], special: []};
        for (const p of this.s.parameterTypes) {
            if (p.kind === 'ENUM') groups.enums.push(p);
            else if (!p.kind || p.kind === 'COMPOSITE') groups.objects.push(p);
            else groups.special.push(p);
        }
        const sections = [];
        const group = (title, id, intro, bodies) => {
            if (!bodies.length) return;
            sections.push(`## ${esc(title)} {#${id}}\n\n${esc(intro)}\n\n${bodies.join('\n\n')}`);
        };
        group(ui.groupBasic, ui.groupBasicId, ui.groupBasicIntro, this.basicIds.map(id => this.typeSection({type: id}, bucket)));
        const coll = [['ARRAY', ui.list, ui.listDesc], ['MAP', ui.map, ui.mapDesc]].map(([id, n, d]) => `### ${esc(n)} {#${id}}\n\n${esc(d)}`);
        group(ui.groupCollections, ui.groupCollectionsId, ui.groupCollectionsIntro, coll);
        group(ui.groupEnums, ui.groupEnumsId, ui.groupEnumsIntro, groups.enums.map(p => this.typeSection(p, bucket)));
        group(ui.groupObjects, ui.groupObjectsId, ui.groupObjectsIntro, groups.objects.map(p => this.typeSection(p, bucket)));
        group(ui.groupSpecial, ui.groupSpecialId, ui.groupSpecialIntro, groups.special.map(p => this.typeSection(p, bucket)));

        const overview = table(
            [ui.name, ui.details],
            [
                [`[${esc(ui.groupBasic, true)}](#${ui.groupBasicId})`, esc(ui.groupBasicIntro, true)],
                [`[${esc(ui.groupCollections, true)}](#${ui.groupCollectionsId})`, esc(ui.groupCollectionsIntro, true)],
                [`[${esc(ui.groupEnums, true)}](#${ui.groupEnumsId})`, esc(ui.groupEnumsIntro, true)],
                [`[${esc(ui.groupObjects, true)}](#${ui.groupObjectsId})`, esc(ui.groupObjectsIntro, true)],
                [`[${esc(ui.groupSpecial, true)}](#${ui.groupSpecialId})`, esc(ui.groupSpecialIntro, true)]
            ].filter((_, i) => [groups.basic.length || this.basicIds.length, true, groups.enums.length, groups.objects.length, groups.special.length][i])
        );
        const override = this.readOverride('value-types.md');
        const intro = override != null ? override : esc(ui.valueTypesIntro);
        const head = [
            '---',
            'sidebar_position: 12',
            `title: ${yamlStr(ui.valueTypesTitle)}`,
            `sidebar_label: ${yamlStr(ui.valueTypesLabel)}`,
            `description: ${yamlStr(ui.valueTypesDescription)}`,
            '---'
        ].join('\n');
        return {rel: 'value-types.md', content: `${head}\n\n${this.banner()}\n\n${intro}\n\n${overview}\n\n${sections.join('\n\n')}\n`};
    }

    // ----- reports
    countExtras() {
        const ids = {
            categories: new Set(),
            parameterTypes: new Set(this.s.parameterTypes.map(p => p.type)),
            triggers: new Set(this.s.triggers.map(t => t.id)),
            actions: new Set(this.s.actions.map(a => a.id))
        };
        const walk = (list) => list.forEach(c => {
            ids.categories.add(c.id);
            if (c.items) walk(c.items);
        });
        walk(this.s.categories);
        const res = {};
        for (const k of Object.keys(ids)) {
            const keys = Object.keys(this.l[k] || {});
            if (k === 'categories') {
                // nested leaf entries live inside the parent entry
                res[k] = keys.filter(x => !ids.categories.has(x));
            } else if (k === 'parameterTypes') {
                res[k] = keys.filter(x => !ids[k].has(x) && !this.basicIds.includes(x));
            } else res[k] = keys.filter(x => !ids[k].has(x));
            res[k + 'Missing'] = [...ids[k]].filter(x => !(this.l[k] || {})[x] && !(k === 'categories'));
        }
        return res;
    }
}

