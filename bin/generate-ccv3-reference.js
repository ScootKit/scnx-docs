function writeIfChanged(file, content) {
    fs.mkdirSync(path.dirname(file), {recursive: true});
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
    fs.writeFileSync(file, content);
    return true;
}

function removeStale(outDir, produced) {
    const removed = [];
    const walk = (dir, rel) => {
        if (!fs.existsSync(dir)) return;
        for (const e of fs.readdirSync(dir, {withFileTypes: true})) {
            const r = `${rel}/${e.name}`;
            const full = path.join(dir, e.name);
            if (e.isDirectory()) {
                walk(full, r);
                if (!fs.readdirSync(full).length) fs.rmdirSync(full);
                continue;
            }
            if (produced.has(r)) continue;
            const isMd = e.name.endsWith('.md') && fs.readFileSync(full, 'utf8').includes(BANNER_MARK);
            const isCat = e.name === '_category_.json' && fs.readFileSync(full, 'utf8').includes('"ccv3-reference"');
            if (isMd || isCat) {
                fs.unlinkSync(full);
                removed.push(r);
            }
        }
    };
    walk(path.join(outDir, 'reference'), 'reference');
    return removed;
}

async function main() {
    const opts = parseArgs(process.argv.slice(2));
    const [schema, loc] = await Promise.all([
        loadJSON(opts.source, 'custom-command-data.json'),
        loadJSON(opts.source, `localized-custom-commands/${opts.locale}.json`)
    ]);
    const outDir = opts.out
        ? path.resolve(opts.out)
        : opts.locale === 'en'
            ? path.join(ROOT, 'docs', 'custom-commands')
            : path.join(ROOT, 'i18n', opts.locale, 'docusaurus-plugin-content-docs', 'current', 'custom-commands');

    const gen = new Generator(schema, loc, opts.locale);
    const pages = [...gen.generateReferencePages(), gen.generateValueTypes()];
    const produced = new Set(pages.map(p => p.rel));
    let written = 0;
    for (const p of pages) if (writeIfChanged(path.join(outDir, p.rel), p.content)) written++;
    const removed = removeStale(outDir, produced);

    const count = (sub) => pages.filter(p => p.rel.startsWith(sub) && p.rel.endsWith('.md')).length;
    console.log(`CCV3 reference generated from schema ${schema.version} (locale ${opts.locale}, source ${opts.source})`);
    console.log(`Output: ${outDir}`);
    console.log(`Pages: ${count('reference/triggers/')} trigger pages (${schema.triggers.length} triggers), ` +
        `${count('reference/actions/')} action pages (${schema.actions.length} actions), value-types.md (${schema.parameterTypes.length} schema types + ${gen.basicIds.length} basic types)`);
    console.log(`Files changed: ${written}, stale removed: ${removed.length}${removed.length ? ' (' + removed.join(', ') + ')' : ''}`);

    const ex = gen.countExtras();
    console.log('Locale entries not in the schema (ignored): ' +
        `categories ${ex.categories.length}, parameterTypes ${ex.parameterTypes.length}, triggers ${ex.triggers.length}, actions ${ex.actions.length}`);
    for (const k of ['triggers', 'actions', 'parameterTypes']) {
        if (ex[k + 'Missing'].length) console.log(`Schema ${k} without any locale entry: ${ex[k + 'Missing'].length} (${ex[k + 'Missing'].slice(0, 10).join(', ')})`);
    }
    if (gen.unmatched && gen.unmatched.length) console.log(`Actions not matched by any data-tools group (placed in "More data tools"): ${gen.unmatched.join(', ')}`);
    if (gen.unknownCategories.length) {
        console.log(`Categories used by items but missing in the schema category tree: ${gen.unknownCategories.join(', ')}`);
    }
    if (gen.warnings.size) {
        let total = 0;
        const lines = [];
        for (const [bucket, m] of [...gen.warnings.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
            const parts = [...m.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([w, n]) => {
                total += n;
                return `${w} x${n}`;
            });
            lines.push(`  ${bucket}: ${parts.join(', ')}`);
        }
        console.log(`Warnings (missing localized text, omitted): ${total}`);
        console.log(lines.join('\n'));
    } else console.log('Warnings: none');
}

main().catch(err => {
    console.error(err.message || err);
    process.exit(1);
});
