#!/usr/bin/env node
/**
 * Generates the Custom Commands v3 (CCV3) reference pages from the CCV3 schema.
 *
 * Inputs (two JSON files):
 *   - custom-command-data.json                       (structure: version, categories, parameterTypes, triggers, actions)
 *   - localized-custom-commands/<locale>.json        (names + descriptions: categories, parameterTypes, triggers, actions)
 *
 * The files are read from a directory or from a URL base (fetched over HTTP), chosen by, in order:
 *   --source <dir-or-url-base>  |  CCV3_SCHEMA_SOURCE  |  /home/simonc/workspace/CustomDCBotPrivate-v3
 * The schema ids decide what is documented. Locale entries that are not in the schema are ignored (and counted).
 *
 * Output (English, default) in docs/custom-commands/:
 *   reference/triggers/<category-id>.md   one page per category that has triggers
 *   reference/actions/<category-id>.md    one page per category that has actions
 *   value-types.md                        all parameter types
 * With --locale de the same files are written to
 *   i18n/de/docusaurus-plugin-content-docs/current/custom-commands/
 * Use --out <dir> to write somewhere else (the dir that replaces custom-commands/).
 *
 * Optional hand-written intros live in bin/ccv3-reference/overrides/:
 *   <kind>/<category-id>.md  (kind = triggers | actions)   and   value-types.md
 * For a non-English locale the file is looked up under overrides/<locale>/ instead (no fallback to English).
 * An override body replaces the generated intro paragraph under the title.
 *
 * Only generated files (those carrying the banner) are ever deleted, and only when they are stale.
 * Output is deterministic: running it twice yields no diff.
 *
 * Usage: node bin/generate-ccv3-reference.js [--source <dir|url>] [--locale en|de] [--out <dir>]
 */
